    private void checkoutButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_checkoutButtonActionPerformed
        // Generated with assistance from Claude
        if (cart.getItems().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Your cart is empty. Add some items first.", "Empty cart", JOptionPane.WARNING_MESSAGE);
            return;
        }
        JTextField cardField = new JTextField(16);
        JTextField cvcField = new JTextField(3);
        JTextField monthField = new JTextField(2);
        JTextField yearField = new JTextField(4);
        JPanel form = new JPanel(new GridLayout(0, 2, 5, 5));
        form.add(new JLabel("Card number (16 digits):")); form.add(cardField);
        form.add(new JLabel("CVC (3 digits):")); form.add(cvcField);
        form.add(new JLabel("Expiry month (1-12):")); form.add(monthField);
        form.add(new JLabel("Expiry year (e.g. 2028):")); form.add(yearField);

        LocalDate expiry;
        while (true) { //keeps asking until the details are valid, or the customer cancels
            int choice = JOptionPane.showConfirmDialog(this, form,
                    String.format("Pay $%.2f", cart.getTotal()), JOptionPane.OK_CANCEL_OPTION, JOptionPane.PLAIN_MESSAGE);
            if (choice != JOptionPane.OK_OPTION) {
                return; //cancelled, back to the cart
            }
            String error = null;
            expiry = null;
            if (!cardField.getText().trim().matches("[0-9]{16}")) {
                error = "Card number must be exactly 16 digits.";
            } else if (!cvcField.getText().trim().matches("[0-9]{3}")) {
                error = "CVC must be exactly 3 digits.";
            } else {
                try {
                    int month = Integer.parseInt(monthField.getText().trim());
                    int year = Integer.parseInt(yearField.getText().trim());
                    expiry = LocalDate.of(year, month, 1); //throws if the month is out of range
                } catch (NumberFormatException | java.time.DateTimeException e) {
                    error = "Please enter a valid expiry month (1-12) and year.";
                }
            }
            if (error == null) {
                break;
            }
            JOptionPane.showMessageDialog(this, error, "Check your details", JOptionPane.ERROR_MESSAGE);
        }

        Payment payment = new Payment(cardField.getText().trim(), cvcField.getText().trim(), expiry, cart.getTotal());
        Order order = frame.getOrderService().placeOrder((Customer) frame.getCurrentUser(), cart, payment);

        if (order != null) {
            JOptionPane.showMessageDialog(this, "Order #" + order.getId() + " placed successfully!");
            cart.clear();
            refreshCart();
            loadOrders(); //so the new order appears straight away
        } else {
            JOptionPane.showMessageDialog(this, "Payment was declined. Check that the card hasn't expired.", "Payment failed", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_checkoutButtonActionPerformed

