    public void onShow() { //called by MainFrame every time this screen is opened after a login
        Customer customer = (Customer) frame.getCurrentUser();
        welcomeLabel.setText("Welcome, " + customer.getUsername());
        cart.clear(); //a new login always starts with an empty cart
        loadMenu();
        refreshCart();
        loadOrders();
    }
    // Generated with assistance from Claude
    private void loadMenu() {
        menuModel.setRowCount(0); //wipe the old rows first
        for (MenuItem item : frame.getMenuService().getAllItems()) {
            menuModel.addRow(new Object[]{
                item.getId(), item.getName(), item.getCategory(), String.format("$%.2f", item.getPrice())});
        }
    }
    // Generated with assistance from Claude
    private void refreshCart() {
        cartModel.setRowCount(0);
        for (OrderLine line : cart.getItems()) {
            cartModel.addRow(new Object[]{
                line.getMenuItem().getName(), line.getQuantity(), String.format("$%.2f", line.getLineTotal())});
        }
        totalLabel.setText(String.format("Total: $%.2f", cart.getTotal()));
    }
    // Generated with assistance from Claude
    private void loadOrders() {
        ordersModel.setRowCount(0);
        Customer customer = (Customer) frame.getCurrentUser();
        for (Order order : frame.getOrderService().getOrdersByCustomer(customer)) {
            String delivery;
            if (order.getStatus() == OrderStatus.DELIVERED) {
                delivery = order.getDeliveryTime().toString(); //the real delivery date
            } else if (order.getStatus() == OrderStatus.READY) {
                delivery = "Ready now";
            } else {
                delivery = "Est. " + frame.getOrderService().getEstimatedWaitMinutes() + " min"; //same queue estimate as the CUI
            }
            ordersModel.addRow(new Object[]{
                order.getId(), order.getStatus(), order.getOrderTime(), delivery,
                String.format("$%.2f", order.getTotalAmount())});
        }
    }

