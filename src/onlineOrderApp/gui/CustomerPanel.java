    private void deleteAccountButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteAccountButtonActionPerformed
        int answer = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete your account?", "Delete account", JOptionPane.YES_NO_OPTION);
        if (answer != JOptionPane.YES_OPTION) {
            return;
        }
        String username = frame.getCurrentUser().getUsername();
        if (frame.getAuthService().deleteUser(username)) {
            JOptionPane.showMessageDialog(this, "Account deleted.");
            cart.clear();
            frame.setCurrentUser(null);
            frame.showScreen("login");
        } else {
            JOptionPane.showMessageDialog(this, "Could not delete account. Accounts with past orders must be kept for order records.", "Delete failed", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_deleteAccountButtonActionPerformed

    private void addToCartButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addToCartButtonActionPerformed
        int row = menuTable.getSelectedRow();
        if (row == -1) { //nothing clicked in the menu table
            JOptionPane.showMessageDialog(this, "Select an item from the menu first.", "No item selected", JOptionPane.WARNING_MESSAGE);
            return;
        }
        int itemId = (int) menuModel.getValueAt(menuTable.convertRowIndexToModel(row), 0); //column 0 is the ID
        int quantity = (int) quantitySpinner.getValue();

        for (MenuItem item : frame.getMenuService().getAllItems()) {
            if (item.getId() == itemId) {
                cart.addItem(item, quantity);
                refreshCart();
                return;
            }
        }
        JOptionPane.showMessageDialog(this, "That item is no longer on the menu.", "Item not found", JOptionPane.ERROR_MESSAGE);
        loadMenu(); //the menu changed underneath us, so reload it
    }//GEN-LAST:event_addToCartButtonActionPerformed

    private void removeItemButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removeItemButtonActionPerformed
        int row = cartTable.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Select an item in your cart first.", "No item selected", JOptionPane.WARNING_MESSAGE);
            return;
        }
        OrderLine line = cart.getItems().get(cartTable.convertRowIndexToModel(row)); //table rows are in the same order as the cart
        cart.removeItem(line);
        refreshCart();
    }//GEN-LAST:event_removeItemButtonActionPerformed

