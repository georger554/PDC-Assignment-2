    private void registerButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_registerButtonActionPerformed
        //generated by AI
        String type = (String) typeBox.getSelectedItem();
        String username = usernameField.getText().trim();
        String password = new String(passwordField.getPassword());
        String email = emailField.getText().trim();
        String address = addressField.getText().trim();
        String phone = phoneField.getText().trim();

        if (username.isEmpty() || password.isEmpty() || email.isEmpty()) { //these three are needed for every account
            showError("Username, password and email can't be empty.");
            return;
        }

        if (!email.contains("@")) { //same rule as the CUI
            showError("Email must contain '@'.");
            return;
        }

        if (type.equals("CUSTOMER")) { //only customers need an address and phone number
            if (address.isEmpty()) {
                showError("Please enter an address.");
                return;
            }
            if (!phone.matches("[0-9]+")) {
                showError("Phone number must contain digits only.");
                return;
            }
        }

        boolean ok = frame.getAuthService().register(type, username, password, email, address, phone, "");

        if (ok) {
            JOptionPane.showMessageDialog(this, "Registration successful! Please log in.", "Success", JOptionPane.INFORMATION_MESSAGE);
            usernameField.setText(""); //clear the form for next time
            passwordField.setText("");
            emailField.setText("");
            addressField.setText("");
            phoneField.setText("");
            frame.showScreen("login");
        }
        else {
            showError("Username already taken.");
        }
    }

