    private void loginButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginButtonActionPerformed
        // Generated with assistance from Claude
        String username = usernameField.getText().trim();
        String password = new String(passwordField.getPassword()); //getPassword gives a char[], so convert it

        if (username.isEmpty() || password.isEmpty()) { //both fields must be filled in
            JOptionPane.showMessageDialog(this, "Please enter both a username and a password.", "Login failed", JOptionPane.ERROR_MESSAGE);
            return;
        }

        User user = frame.getAuthService().login(username, password); //same login call the CUI used

        if (user == null) { //wrong username or password
            JOptionPane.showMessageDialog(this, "Invalid username or password.", "Login failed", JOptionPane.ERROR_MESSAGE);
            return;
        }

        frame.setCurrentUser(user); //remember who is logged in
        usernameField.setText(""); //clear the fields so the next login starts empty
        passwordField.setText("");

        if (user instanceof Admin) {
            frame.showScreen("admin");
        } else {
            frame.openCustomerScreen();
        }
    }//GEN-LAST:event_loginButtonActionPerformed

